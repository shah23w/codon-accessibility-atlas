#!/usr/bin/env python3
"""
step4_04_robustness.py: is the core result robust to codon-call error?

step4_02 measured how often an independent assembly reproduces each codon call. This
step asks the question that actually matters for the conclusion: does the Step-3 result
survive when the analysis is restricted to codon calls that an INDEPENDENT assembly
confirms?

If the effect were being generated by assembly or annotation error, restricting to
replicated calls should weaken it. If the effect is real, restricting to the
highest-confidence subset should leave it intact or strengthen it.

Also reported:
  * the same test restricted to VGSC, the gene with the highest replication rate and the
    only gene carrying the confirmatory test;
  * per-gene replication rates, so the reliability of every gene in the atlas is on the
    record rather than assumed.

Outputs
-------
results/robustness_replicated_subset.csv
logs/step4_04_robustness.log
"""
from __future__ import annotations

import csv
import os
import random
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from atlas_common import (  # noqa: E402
    DIR_PROC, DIR_RESULTS, Tee, cluster_bootstrap_ci, ensure_dirs,
)
from codon_engine import codon_reaches  # noqa: E402
from step9_01_corrected_statistics import poisson_binomial_sf  # noqa: E402

N_PERM = 100_000
SEED = 20260729



def exact_accessibility_probs(events, pools):
    """Per-event accessibility probability under the SAME null the permutation
    samples from: one codon drawn uniformly from that site's wild-type pool.

    P(accessible) is therefore the fraction of the pool that reaches the allele,
    the accessible count is a sum of independent Bernoullis, and its tail is
    exact by Poisson-binomial convolution. The permutation above is a Monte
    Carlo estimate of that same quantity, so it cannot be more accurate and it
    reports the floor 1/(n_perm + 1) whenever there are no exceedances.
    sum(ps) must agree with the permutation's expected value to within Monte
    Carlo error; that agreement is the check that the two constructions are the
    same null.
    """
    ps = []
    for e in events:
        pool = pools.get((e["gene"], e["site_label"]))
        if not pool:
            ps.append(0.0)
            continue
        ps.append(sum(1 for c in pool if codon_reaches(c, e["resistance_allele"]))
                  / len(pool))
    return ps

def perm(events, pools, rng, n_perm=N_PERM):
    if not events:
        return None
    obs = sum(1 for e in events if e["accessible"])
    ge, tot = 0, 0
    for _ in range(n_perm):
        s = 0
        for e in events:
            p = pools.get((e["gene"], e["site_label"]))
            if p:
                s += codon_reaches(rng.choice(p), e["resistance_allele"])
        tot += s
        if s >= obs:
            ge += 1
    exp = tot / n_perm
    ps_ = exact_accessibility_probs(events, pools)
    # A species contributing several events is not several independent draws,
    # and the exact P above conditions on independence between events. The
    # interval resamples whole species so that the figure can show how much of
    # each stratum's precision is real.
    ci_lo, ci_hi = cluster_bootstrap_ci([e["species"] for e in events],
                                        [e["accessible"] for e in events], ps_)
    return {"n_events": len(events), "n_accessible": obs,
            "ci_lo": ci_lo, "ci_hi": ci_hi,
            "frac_accessible": round(obs / len(events), 4),
            "expected_null": round(exp, 3),
            "frac_expected": round(exp / len(events), 4),
            "enrichment": round(obs / exp, 3) if exp else "",
            "p_permutation": (ge + 1) / (n_perm + 1),
            "expected_exact": round(sum(ps_), 3),
            "p_exact": poisson_binomial_sf(ps_, obs),
            "n_perm": n_perm,
            "p_permutation_floor": 1.0 / (n_perm + 1)}


def main():
    import argparse as _ap
    _p = _ap.ArgumentParser()
    _p.add_argument("--atlas", default="codon_atlas.csv")
    _p.add_argument("--events", default="core_test_events.csv")
    _p.add_argument("--tag", default="")
    _a = _p.parse_args()
    ensure_dirs()
    log = Tee("step4_04_robustness" + _a.tag)
    log("=== Step 4.4  robustness of the core result to codon-call error ===\n")
    rng = random.Random(SEED)

    pools = defaultdict(list)
    with open(os.path.join(DIR_PROC, _a.atlas)) as fh:
        for r in csv.DictReader(fh):
            if r["is_wildtype"] == "True":
                pools[(r["gene"], r["site_label"])].append(r["codon"])

    with open(os.path.join(DIR_RESULTS, _a.events)) as fh:
        events = list(csv.DictReader(fh))
    for e in events:
        e["accessible"] = e["accessible"] == "True"
    log(f"core events: {len(events)}")

    # replication status per (species, gene, site)
    rep = {}
    path = os.path.join(DIR_RESULTS, "assembly_replication" + _a.tag + ".csv")
    if not os.path.exists(path):
        log("assembly_replication.csv not found - run step4_02 first")
        return
    with open(path) as fh:
        for r in csv.DictReader(fh):
            rep[(r["species"], r["gene"], r["site_label"])] = (
                r["aa_agree"] == "True", r["codon_agree"] == "True")
    log(f"replicated site calls available: {len(rep)}")

    have = [e for e in events if (e["species"], e["gene"], e["site_label"]) in rep]
    conf_aa = [e for e in have
               if rep[(e["species"], e["gene"], e["site_label"])][0]]
    conf_codon = [e for e in have
                  if rep[(e["species"], e["gene"], e["site_label"])][1]]
    log(f"\n  events with an independent replicate : {len(have)}")
    log(f"  ... amino acid confirmed              : {len(conf_aa)}")
    log(f"  ... exact codon confirmed             : {len(conf_codon)}")
    log(f"  species involved                      : "
        f"{len({e['species'] for e in have})}")

    # A GCA/GCF twin is the same DNA under two accessions and a version bump
    # is the same submission resequenced by the archive, so neither replicates
    # a call. step2_01 classifies every pair; of the 41 codon-confirmed events
    # only 30 rest on an independently sequenced assembly. The strictest
    # stratum above counts all 41, so this one is added rather than
    # substituted, and the figure can show both.
    pair_class = {}
    pc_path = os.path.join(DIR_RESULTS, "assembly_replication_pair_classes.csv")
    if os.path.exists(pc_path):
        with open(pc_path) as fh:
            for r in csv.DictReader(fh):
                pair_class[r["species"].strip()] = r["pair_class"].strip()
        conf_codon_indep = [e for e in conf_codon
                            if pair_class.get(e["species"]) == "INDEPENDENT"]
        log(f"  ... of those, independently sequenced : {len(conf_codon_indep)}"
            f"  (dropped {len(conf_codon) - len(conf_codon_indep)} twin or "
            f"version-bump pairs)")
    else:
        conf_codon_indep = []
        log("  assembly_replication_pair_classes.csv not found - the "
            "independent-only stratum is skipped")

    rows = []
    strata = [
        ("all events", events),
        ("has independent replicate", have),
        ("amino acid replicated", conf_aa),
        ("CODON replicated (strictest)", conf_codon),
        ("CODON replicated, independent assemblies only", conf_codon_indep),
        ("VGSC only", [e for e in events if e["gene"] == "VGSC"]),
        ("VGSC + codon replicated", [e for e in conf_codon if e["gene"] == "VGSC"]),
    ]
    log(f"\n  {'stratum':30s} {'n':>4s} {'acc':>4s} {'obs%':>6s} {'null%':>6s} {'enrich':>7s} {'p':>10s}")
    for label, sub in strata:
        if len(sub) < 4:
            log(f"  {label:30s} n={len(sub)} - too few, skipped")
            continue
        r = perm(sub, pools, rng)
        log(f"  {label:30s} {r['n_events']:4d} {r['n_accessible']:4d} "
            f"{r['frac_accessible']:6.1%} {r['frac_expected']:6.1%} "
            f"{r['enrichment']:7} {r['p_permutation']:10.6f}")
        rows.append({"stratum": label, **r})

    out = os.path.join(DIR_RESULTS, "robustness_replicated_subset" + _a.tag + ".csv")
    with open(out, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader(); w.writerows(rows)
    log(f"\nwrote {out}")

    # per-gene replication rates, for the record
    log("\n--- per-gene replication (all atlas sites, not only tested ones) ---")
    per = defaultdict(lambda: [0, 0, 0])
    with open(path) as fh:
        for r in csv.DictReader(fh):
            g = per[r["gene"]]
            g[0] += 1
            g[1] += r["aa_agree"] == "True"
            g[2] += r["codon_agree"] == "True"
    log(f"  {'gene':10s} {'n':>5s} {'aa':>8s} {'codon':>8s}")
    for g, (n, aa, cd) in sorted(per.items(), key=lambda kv: -kv[1][0]):
        log(f"  {g:10s} {n:5d} {aa/n:8.2%} {cd/n:8.2%}")
    log.close()


if __name__ == "__main__":
    main()
